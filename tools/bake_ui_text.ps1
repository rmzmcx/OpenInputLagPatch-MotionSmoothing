param(
    [string]$InputPath = (Join-Path $env:APPDATA 'ShanghaiAlice\oilp_custom\ui_text.ini'),
    [string]$OutputPath = ''
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
if ([string]::IsNullOrWhiteSpace($OutputPath)) {
    $OutputPath = Join-Path $root 'openinputlagpatch\ui_text_baked.inc'
}
if (-not (Test-Path -LiteralPath $InputPath)) {
    throw "ui_text.ini not found: $InputPath"
}

$languages = @{ zh = 0; en = 1; ja = 2 }
$language = -1
$items = New-Object System.Collections.Generic.List[object]

function Unescape-Text([string]$text) {
    $out = New-Object System.Text.StringBuilder
    for ($i = 0; $i -lt $text.Length; ++$i) {
        if ($text[$i] -ne '\' -or $i + 1 -ge $text.Length) {
            [void]$out.Append($text[$i])
            continue
        }
        ++$i
        switch ($text[$i]) {
            'n' { [void]$out.Append("`n") }
            'r' { [void]$out.Append("`r") }
            't' { [void]$out.Append("`t") }
            '\' { [void]$out.Append('\') }
            default { [void]$out.Append($text[$i]) }
        }
    }
    return $out.ToString()
}

function Escape-C([string]$text) {
    return $text.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t')
}

foreach ($raw in Get-Content -LiteralPath $InputPath -Encoding UTF8) {
    $line = $raw.Trim()
    if ($line.Length -eq 0 -or $line.StartsWith(';') -or $line.StartsWith('#')) {
        continue
    }
    if ($line.StartsWith('[') -and $line.EndsWith(']')) {
        $section = $line.Substring(1, $line.Length - 2).ToLowerInvariant()
        if ($languages.ContainsKey($section)) {
            $language = $languages[$section]
        } else {
            $language = -1
        }
        continue
    }
    if ($language -lt 0) {
        continue
    }
    $equals = $line.IndexOf('=')
    if ($equals -lt 0) {
        continue
    }
    $key = $line.Substring(0, $equals).Trim()
    $value = Unescape-Text $line.Substring($equals + 1).Trim()
    if ($key.Length -eq 0 -or $value.Length -eq 0) {
        continue
    }
    $items.Add([pscustomobject]@{ Id = $key; Language = $language; Text = $value })
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('// Generated by tools/bake_ui_text.ps1 for Release builds. Do not edit by hand.')
$lines.Add('static const BakedText kBakedTexts[] = {')
foreach ($item in ($items | Sort-Object Id, Language)) {
    $key = Escape-C $item.Id
    $value = Escape-C $item.Text
    $lines.Add("`t{ `"$key`", $($item.Language), `"$value`" },")
}
$lines.Add("`t{ nullptr, 0, nullptr },")
$lines.Add('};')
$lines.Add('')

$parent = Split-Path -Parent $OutputPath
if (-not (Test-Path -LiteralPath $parent)) {
    New-Item -ItemType Directory -Path $parent | Out-Null
}
[IO.File]::WriteAllLines($OutputPath, $lines, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "baked $($items.Count) text override(s) from $InputPath"
Write-Output "wrote $OutputPath"
